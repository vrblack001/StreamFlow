package dev.streamflow.android.data.model

import com.google.gson.annotations.SerializedName

// ─────────────────────────────────────────────────────────────
// Piped API response models
// Mirrors https://piped.video/api/v1/ endpoint schemas
// ─────────────────────────────────────────────────────────────

data class StreamResponse(
    val title: String = "",
    val description: String = "",
    val uploadDate: String = "",
    val uploader: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatar: String = "",
    val uploaderVerified: Boolean = false,
    val thumbnail: String = "",
    val duration: Long = 0L,
    val views: Long = 0L,
    val likes: Long = 0L,
    val dislikes: Long = 0L,          // from Return YouTube Dislike
    val hls: String? = null,
    val dash: String? = null,
    val videoStreams: List<VideoStream> = emptyList(),
    val audioStreams: List<AudioStream> = emptyList(),
    val relatedStreams: List<StreamItem> = emptyList(),
    val chapters: List<Chapter> = emptyList(),
    val subtitles: List<Subtitle> = emptyList(),
    val livestream: Boolean = false,
    val proxyUrl: String = ""
)

data class VideoStream(
    val url: String = "",
    val quality: String = "",
    val mimeType: String = "",
    val codec: String = "",
    val videoOnly: Boolean = false,
    val width: Int = 0,
    val height: Int = 0,
    val fps: Int = 0,
    val bitrate: Int = 0,
    val indexStart: Long = 0,
    val indexEnd: Long = 0,
    val initStart: Long = 0,
    val initEnd: Long = 0
)

data class AudioStream(
    val url: String = "",
    val format: String = "",
    val quality: String = "",
    val mimeType: String = "",
    val codec: String = "",
    val audioTrackId: String? = null,
    val audioTrackName: String? = null,
    val audioTrackType: String? = null,
    val audioTrackLocale: String? = null,
    val videoOnly: Boolean = false,
    val itag: Int = 0,
    val bitrate: Int = 0,
    val initStart: Long = 0,
    val initEnd: Long = 0,
    val indexStart: Long = 0,
    val indexEnd: Long = 0
)

data class StreamItem(
    val url: String = "",
    val type: String = "stream",
    val title: String = "",
    val thumbnail: String = "",
    val uploaderName: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatar: String? = null,
    val uploaderVerified: Boolean = false,
    val duration: Long = 0L,
    val views: Long = 0L,
    val uploaded: Long = 0L,
    val uploadedDate: String? = null,
    val shortDescription: String? = null,
    val isShort: Boolean = false
) {
    /** Extract YouTube video ID from /watch?v= URLs */
    val videoId: String get() = url.substringAfterLast("=")
}

data class Chapter(
    val title: String = "",
    val image: String = "",
    val start: Long = 0L
)

data class Subtitle(
    val url: String = "",
    val mimeType: String = "",
    val name: String = "",
    val code: String = "",
    val autoGenerated: Boolean = false
)

data class Channel(
    val id: String = "",
    val name: String = "",
    val avatarUrl: String = "",
    val bannerUrl: String = "",
    val description: String = "",
    val subscriberCount: Long = 0L,
    val verified: Boolean = false,
    val tabs: List<ChannelTab> = emptyList(),
    val relatedStreams: List<StreamItem> = emptyList(),
    val nextpage: String? = null
)

data class ChannelTab(
    val name: String = "",
    val data: String = ""
)

data class SearchResult(
    val items: List<StreamItem> = emptyList(),
    val nextpage: String? = null,
    val suggestion: String? = null,
    val corrected: Boolean = false
)

data class TrendingResponse(
    val trending: List<StreamItem> = emptyList()
)

data class PlaylistResponse(
    val name: String = "",
    val thumbnailUrl: String = "",
    val bannerUrl: String? = null,
    val uploader: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatar: String? = null,
    val videos: Long = 0L,
    val relatedStreams: List<StreamItem> = emptyList(),
    val nextpage: String? = null
)

data class CommentsResponse(
    val comments: List<Comment> = emptyList(),
    val nextpage: String? = null,
    val disabled: Boolean = false
)

data class Comment(
    val author: String = "",
    val thumbnail: String = "",
    val commentId: String = "",
    val commentText: String = "",
    val commentedTime: String = "",
    val likeCount: Long = 0L,
    val replyCount: Int = 0,
    val isPinned: Boolean = false,
    val isHearted: Boolean = false,
    val isUploaderVerified: Boolean = false
)

/** SponsorBlock segment */
data class SponsorSegment(
    val category: String,
    val actionType: String,
    @SerializedName("segment") val range: List<Float>,
    val UUID: String,
    val locked: Int,
    val votes: Int,
    val videoDuration: Float,
    val userID: String? = null
) {
    val startMs: Long get() = (range.getOrElse(0) { 0f } * 1000).toLong()
    val endMs: Long   get() = (range.getOrElse(1) { 0f } * 1000).toLong()
}

/** Return YouTube Dislike response */
data class RydResponse(
    val id: String = "",
    val dateCreated: String = "",
    val likes: Long = 0L,
    val dislikes: Long = 0L,
    val rating: Double = 0.0,
    val viewCount: Long = 0L,
    val deleted: Boolean = false
)

/** DeArrow title/thumbnail replacement */
data class DeArrowResponse(
    val titles: List<DeArrowTitle> = emptyList(),
    val thumbnails: List<DeArrowThumbnail> = emptyList()
)

data class DeArrowTitle(
    val title: String = "",
    val original: Boolean = false,
    val votes: Int = 0,
    val locked: Boolean = false,
    val UUID: String = ""
)

data class DeArrowThumbnail(
    val timestamp: Float? = null,
    val original: Boolean = false,
    val votes: Int = 0,
    val locked: Boolean = false,
    val UUID: String = ""
)
